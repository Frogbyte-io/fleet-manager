<script setup lang="ts">
import { useQuery, useQueryClient } from '@tanstack/vue-query'
import { computed, ref, watch } from 'vue'

import {
  createMachine,
  listProxmoxAccounts,
  reviewMachineCreate,
  type MachineCreateReviewDto,
  type OperationDto,
  type PageProxmoxAccountDtoItemsItem,
} from '@frogbyte-io/fleet-api-client'
import { Dialog, DialogContent, DialogDescription, DialogTitle } from '@/components/ui/dialog'
import { Input } from '@/components/ui/input'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'

import { errorMessage, unwrap } from '../../machine/api'

// "Create persistent machine": the same two calls `fleetctl machines create`
// makes. The review call validates the spec and answers the exact spec that
// will run with its token; the create call queues the durable operation. The
// dialog never holds a secret: the SSH key is generated by the controller.
const open = defineModel<boolean>('open', { required: true })

const queryClient = useQueryClient()

const accountsQuery = useQuery({
  queryKey: ['fleet', 'persistent', 'accounts'],
  queryFn: async () => {
    const response = await listProxmoxAccounts({ limit: 200 })
    if (response.status !== 200)
      throw new Error(`Accounts could not be loaded (${response.status})`)
    return response.data.items as PageProxmoxAccountDtoItemsItem[]
  },
  enabled: open,
})

const accountId = ref('')
const imageVersionId = ref('')
const name = ref('')
const os = ref<'linux' | 'windows'>('linux')
const cores = ref('')
const memoryMib = ref('')
const diskGib = ref('')
const description = ref('')
const protection = ref(true)

const review = ref<MachineCreateReviewDto | null>(null)
const operation = ref<OperationDto | null>(null)
const error = ref<string | null>(null)
const busy = ref(false)

const accounts = computed(() => accountsQuery.data.value ?? [])

watch(open, (isOpen) => {
  if (isOpen) {
    review.value = null
    operation.value = null
    error.value = null
  }
})

// Editing any field invalidates the review: the token is bound to the spec.
watch([accountId, imageVersionId, name, os, cores, memoryMib, diskGib, description, protection], () => {
  review.value = null
})

function numberOrUndefined(raw: string): number | undefined {
  const value = Number.parseInt(raw, 10)
  return Number.isFinite(value) && value > 0 ? value : undefined
}

function spec(): Record<string, unknown> {
  const body: Record<string, unknown> = {
    accountId: accountId.value,
    imageVersionId: imageVersionId.value.trim(),
    name: name.value.trim(),
    guestOs: os.value,
    protection: protection.value,
  }
  const optional: [string, number | undefined][] = [
    ['cores', numberOrUndefined(cores.value)],
    ['memoryMib', numberOrUndefined(memoryMib.value)],
    ['diskGib', numberOrUndefined(diskGib.value)],
  ]
  for (const [key, value] of optional) {
    if (value !== undefined)
      body[key] = value
  }
  if (description.value.trim())
    body.description = description.value.trim()
  return body
}

const ready = computed(() => accountId.value !== '' && imageVersionId.value.trim() !== '' && name.value.trim() !== '')

async function runReview() {
  busy.value = true
  error.value = null
  try {
    const response = await reviewMachineCreate({ spec: spec() })
    review.value = unwrap<MachineCreateReviewDto>(response)
  }
  catch (cause) {
    review.value = null
    error.value = errorMessage(cause)
  }
  finally {
    busy.value = false
  }
}

async function runCreate() {
  if (!review.value)
    return
  busy.value = true
  error.value = null
  try {
    const response = await createMachine(
      { spec: review.value.spec, reviewToken: review.value.reviewToken },
      { headers: { 'Idempotency-Key': crypto.randomUUID() } },
    )
    operation.value = unwrap<OperationDto>(response, [202])
    await queryClient.invalidateQueries({ queryKey: ['fleet', 'persistent'] })
  }
  catch (cause) {
    error.value = errorMessage(cause)
  }
  finally {
    busy.value = false
  }
}
</script>

<template>
  <Dialog v-model:open="open">
    <DialogContent
      class="max-h-[90vh] overflow-y-auto rounded-sm border-fc-line2 bg-fc-panel p-5 sm:max-w-xl"
      data-testid="create-persistent-dialog"
    >
      <DialogTitle class="text-[17px] font-extrabold text-fc-ink">
        Create persistent machine
      </DialogTitle>
      <DialogDescription class="mb-3 mt-0.5 text-xs text-fc-muted">
        A long-lived VM Fleet keeps: cloned from a promoted image, protected from deletion, never selected by Lab.
        Fleet generates its SSH key and removes the image's shared key.
      </DialogDescription>

      <div
        v-if="operation"
        class="space-y-2 text-xs text-fc-muted"
        data-testid="create-queued"
      >
        <p class="text-sm font-semibold text-fc-ink">
          Creation queued
        </p>
        <p>
          Operation <span class="font-mono text-fc-ink">{{ operation.id }}</span> is {{ operation.state }}.
          Follow it under Operations; the machine appears in the list below once it is registered.
        </p>
        <button
          type="button"
          class="rounded-sm border border-input px-3 py-1.5 font-mono text-[10px] uppercase tracking-wider text-fc-muted hover:border-fc-line2 hover:text-fc-ink"
          @click="open = false"
        >
          Close
        </button>
      </div>

      <form
        v-else
        class="grid gap-3"
        @submit.prevent="review ? runCreate() : runReview()"
      >
        <label class="grid gap-1 text-xs text-fc-muted">
          Proxmox account
          <Select v-model="accountId">
            <SelectTrigger
              class="h-8 text-xs"
              data-testid="pm-account"
            >
              <SelectValue placeholder="Choose an account" />
            </SelectTrigger>
            <SelectContent>
              <SelectItem
                v-for="account in accounts"
                :key="account.id"
                :value="account.id"
              >
                {{ account.name }}
              </SelectItem>
            </SelectContent>
          </Select>
        </label>
        <label class="grid gap-1 text-xs text-fc-muted">
          Promoted image version
          <Input
            v-model="imageVersionId"
            class="h-8 border-input bg-background font-mono text-xs"
            placeholder="version id from Images"
            data-testid="pm-image"
          />
        </label>
        <div class="grid grid-cols-2 gap-3">
          <label class="grid gap-1 text-xs text-fc-muted">
            Name
            <Input
              v-model="name"
              class="h-8 border-input bg-background text-xs"
              placeholder="build-box"
              data-testid="pm-name"
            />
          </label>
          <label class="grid gap-1 text-xs text-fc-muted">
            Guest OS
            <Select v-model="os">
              <SelectTrigger class="h-8 text-xs">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="linux">
                  Linux
                </SelectItem>
                <SelectItem value="windows">
                  Windows (15 character name)
                </SelectItem>
              </SelectContent>
            </Select>
          </label>
        </div>
        <div class="grid grid-cols-3 gap-3">
          <label class="grid gap-1 text-xs text-fc-muted">
            Cores
            <Input
              v-model="cores"
              inputmode="numeric"
              class="h-8 border-input bg-background text-xs"
              placeholder="image"
            />
          </label>
          <label class="grid gap-1 text-xs text-fc-muted">
            Memory (MiB)
            <Input
              v-model="memoryMib"
              inputmode="numeric"
              class="h-8 border-input bg-background text-xs"
              placeholder="image"
            />
          </label>
          <label class="grid gap-1 text-xs text-fc-muted">
            Disk (GiB)
            <Input
              v-model="diskGib"
              inputmode="numeric"
              class="h-8 border-input bg-background text-xs"
              placeholder="image"
            />
          </label>
        </div>
        <label class="grid gap-1 text-xs text-fc-muted">
          Description
          <Input
            v-model="description"
            class="h-8 border-input bg-background text-xs"
          />
        </label>
        <label class="inline-flex items-center gap-2 text-xs text-fc-muted">
          <input
            v-model="protection"
            type="checkbox"
          >
          Protect from deletion
        </label>

        <div
          v-if="review"
          class="rounded-sm border border-fc-line bg-fc-inset p-3 text-xs"
          data-testid="create-review"
        >
          <p class="fc-kicker">
            Reviewed: this is exactly what will run
          </p>
          <pre class="mt-2 max-h-40 overflow-auto whitespace-pre-wrap break-all font-mono text-[11px] text-fc-ink">{{ JSON.stringify(review.spec, null, 2) }}</pre>
        </div>

        <p
          v-if="error"
          class="border-l-2 border-l-fc-err bg-fc-panel px-3 py-1.5 text-xs text-fc-muted"
          role="alert"
          data-testid="create-error"
        >
          {{ error }}
        </p>

        <div class="flex justify-end gap-2">
          <button
            type="button"
            class="rounded-sm border border-input px-3 py-1.5 font-mono text-[10px] uppercase tracking-wider text-fc-muted hover:border-fc-line2 hover:text-fc-ink"
            @click="open = false"
          >
            Cancel
          </button>
          <button
            type="submit"
            class="fc-grad-bg inline-flex h-8 items-center rounded-sm px-4 text-xs font-medium disabled:opacity-50"
            :disabled="!ready || busy"
            data-testid="create-submit"
          >
            {{ review ? 'Create machine' : 'Review' }}
          </button>
        </div>
      </form>
    </DialogContent>
  </Dialog>
</template>
